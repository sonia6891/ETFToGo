import {readFileSync,writeFileSync} from 'node:fs';
import {brotliCompressSync} from 'node:zlib';
import {createHash} from 'node:crypto';
const previous=readFileSync('deploy/legacy-ui-base.ts','utf8');
const boundary=previous.indexOf("const UI_HASH=hash(source['index.html']);");
if(boundary<1000)throw Error('Invalid deployment bootstrap');
const assets=Object.fromEntries(['index.html','manifest.webmanifest','sw.js','install-pocket.html'].map(f=>[f,readFileSync('dist/'+f,'utf8')]));
const raw=Buffer.from(JSON.stringify(assets));
const parts=brotliCompressSync(raw).toString('base64').match(/.{1,9000}/g);
writeFileSync('deploy/assets-v170.json',JSON.stringify(Object.fromEntries(parts.map((part,i)=>['ETF_ASSETS_V170_'+(i+1),part]))));
let code=previous.slice(0,boundary);
code+=`const ui170=brotliDecompressSync(Buffer.from(Array.from({length:${parts.length}},(_,i)=>Bun.env[\`ETF_ASSETS_V170_\${i+1}\`]||'').join(''),'base64'));
if(hash(ui170)!=='${createHash('sha256').update(raw).digest('hex')}')throw Error('UI 1.7.0 checksum mismatch');
Object.assign(source,JSON.parse(ui170.toString('utf8')));
delete source['ETFToGo-Pocket.mobileconfig'];
const UI_HASH=hash(source['index.html']);\n`;
for(const name of ['quote-api.js','catalog-proxy.js','host.js'])code+=readFileSync('server/'+name,'utf8').replace(/^import .*?;\n/gm,'').replace(/\bexport /g,'')+'\n';
code+="await startHost({source,version:'1.7.0',htmlSha256:UI_HASH,origin:'https://etf-independent-app-production.up.railway.app',referenceEndpoint:'http://etf-reference-data.railway.internal:3000/catalog'});\n";
writeFileSync('deploy/railway-v170.ts',code);
console.log({functionBytes:Buffer.byteLength(code),payloadParts:parts.length});
